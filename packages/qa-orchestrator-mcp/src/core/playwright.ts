import { spawnSync } from 'child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { createRequire } from 'module';
import { dirname, join, relative, resolve } from 'path';

/**
 * Pick the Playwright CLI to run tests with. The project's own @playwright/test
 * wins, so its specs and the runner share one copy (two copies make Playwright
 * refuse to run). Projects without one use the copy bundled with this package,
 * and NODE_PATH lets the generated specs `import '@playwright/test'` from it.
 */
export function resolvePlaywright(root: string): { cli: string; env: Record<string, string>; source: 'project' | 'bundled' } {
  try {
    const projectRequire = createRequire(join(root, 'package.json'));
    const pkg = projectRequire.resolve('@playwright/test/package.json');
    return { cli: join(dirname(pkg), 'cli.js'), env: {}, source: 'project' };
  } catch { /* fall back to the bundled copy */ }

  const pkg = require.resolve('@playwright/test/package.json');
  const nodeModules = resolve(dirname(pkg), '..', '..');
  const nodePath = [nodeModules, process.env.NODE_PATH].filter(Boolean).join(process.platform === 'win32' ? ';' : ':');
  return { cli: join(dirname(pkg), 'cli.js'), env: { NODE_PATH: nodePath }, source: 'bundled' };
}

/** Whether the Chromium build this Playwright copy needs has been downloaded. */
export function browserInstalled(root: string): { installed: boolean; executable: string | null } {
  try {
    const { cli } = resolvePlaywright(root);
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const pw = require(join(dirname(cli), 'index.js'));
    const executable: string = pw.chromium.executablePath();
    return { installed: existsSync(executable), executable };
  } catch {
    return { installed: false, executable: null };
  }
}

/** Download the browser(s) for the Playwright copy tests run with. */
export function installBrowsers(root: string, browsers: string[] = ['chromium']): { exitCode: number; output: string } {
  const { cli, env } = resolvePlaywright(root);
  const r = spawnSync(process.execPath, [cli, 'install', ...browsers], {
    cwd: root, encoding: 'utf-8', env: { ...process.env, ...env }, maxBuffer: 16 * 1024 * 1024,
  });
  return { exitCode: r.status ?? 1, output: stripAnsi(`${r.stdout ?? ''}${r.stderr ?? ''}`).slice(-3000) };
}

export interface PlaywrightRun {
  exitCode: number;
  output: string;
  /** Parsed JSON report, or null if Playwright produced none (e.g. it could not start). */
  report: any | null;
}

/**
 * Run Playwright with a JSON report written to `reportFile`.
 * `configFile` is optional: without it Playwright uses the project's own config.
 */
export function runPlaywright(opts: {
  root: string;
  files: string[];
  reportFile: string;
  configFile?: string;
  env?: Record<string, string>;
}): PlaywrightRun {
  const { cli, env } = resolvePlaywright(opts.root);
  mkdirSync(dirname(opts.reportFile), { recursive: true });

  // Playwright reads file arguments as regular expressions matched against posix paths, so an
  // absolute Windows path (full of backslashes) matches nothing. Pass escaped relative paths.
  const filters = opts.files.map(f => relative(opts.root, resolve(opts.root, f)).replace(/\\/g, '/').replace(/[.*+?^${}()|[\]]/g, '\\$&'));
  const args = [cli, 'test', ...(opts.configFile ? ['--config', opts.configFile] : []), '--reporter=json', ...filters];
  const result = spawnSync(process.execPath, args, {
    cwd: opts.root,
    encoding: 'utf-8',
    env: { ...process.env, ...env, ...opts.env, PLAYWRIGHT_JSON_OUTPUT_NAME: opts.reportFile },
    maxBuffer: 64 * 1024 * 1024,
  });

  let report: any | null = null;
  if (existsSync(opts.reportFile)) {
    try { report = JSON.parse(readFileSync(opts.reportFile, 'utf-8')); } catch { /* malformed */ }
  }
  let output = stripAnsi(`${result.stdout ?? ''}${result.stderr ?? ''}${result.error ? `\n${result.error.message}` : ''}`);
  // A run that executed nothing is not a pass: report it as a failed run.
  if (report && flattenReport(report).length === 0) {
    const errors = (report.errors ?? []).map((e: any) => stripAnsi(e.message ?? String(e))).join('\n');
    output = `No tests ran.\n${errors}\n${output}`.trim();
    report = null;
  }
  return { exitCode: result.status ?? 1, output, report };
}

/** Write a Playwright config with no imports, so it loads without resolving @playwright/test. */
export function writeConfig(file: string, config: Record<string, unknown>): string {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `// Generated by qa-orchestrator-mcp — do not edit.\nmodule.exports = ${JSON.stringify(config, null, 2)};\n`, 'utf-8');
  return file;
}

export interface FlatResult {
  title: string;
  file: string;
  status: 'passed' | 'failed' | 'skipped' | 'timedOut' | 'interrupted';
  duration: number;
  error: string | null;
  attachments: { name: string; path?: string }[];
}

/** Flatten a Playwright JSON report to one entry per test (last attempt wins). */
export function flattenReport(report: any): FlatResult[] {
  const out: FlatResult[] = [];
  const walk = (suite: any, file: string) => {
    const f = suite.file ?? file;
    for (const spec of suite.specs ?? []) {
      for (const t of spec.tests ?? []) {
        const r = t.results?.[t.results.length - 1];
        const status = (t.status === 'skipped' ? 'skipped' : r?.status ?? 'skipped') as FlatResult['status'];
        out.push({
          title: spec.title,
          file: f,
          status: t.status === 'flaky' ? 'passed' : status,
          duration: r?.duration ?? 0,
          error: r?.error?.message ? stripAnsi(r.error.message) : r?.errors?.[0]?.message ? stripAnsi(r.errors[0].message) : null,
          attachments: (r?.attachments ?? []).map((a: any) => ({ name: a.name, path: a.path })),
        });
      }
    }
    for (const child of suite.suites ?? []) walk(child, f);
  };
  for (const s of report?.suites ?? []) walk(s, s.file ?? '');
  return out;
}

export function stripAnsi(s: string): string {
  // eslint-disable-next-line no-control-regex
  return s.replace(/\x1b\[[0-9;]*m/g, '');
}
